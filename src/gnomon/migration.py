"""Plan and apply record migrations between published Gnomon contracts.

A migration updates an authored record from a retained logical contract to the current contract of
its record kind. Planning changes only the ``_schema`` binding in memory and validates the result.
It never infers research content. Application preserves every prior file before changing its
contract binding. Generated records are regenerated by their owning command and therefore remain
outside record migration.

Functions
---------
plan_migration
    Inspect a directory and return safe binding changes, blocked records and unreadable files.
apply_migration
    Apply one unchanged plan after preserving the exact prior bytes of every changed record.
"""

from __future__ import annotations

import difflib
import os
import stat
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from yaml.nodes import MappingNode, ScalarNode

from .schemas import (
    identifier,
    load_base,
    published_contracts,
    record_errors,
    record_kinds,
)
from .vocabulary.layout import GENERATED_KINDS


@dataclass(frozen=True)
class MigrationChange:
    """One record whose binding can advance without changing its research content."""

    path: Path
    previous: str
    current: str
    diff: str
    before: bytes
    after: bytes
    backup: Path


@dataclass(frozen=True)
class MigrationBlock:
    """One Gnomon record that requires a researcher to resolve stated defects."""

    path: Path
    previous: str | None
    current: str | None
    reasons: tuple[str, ...]


@dataclass(frozen=True)
class MigrationPlan:
    """Complete write-free migration diagnosis of one directory tree."""

    root: Path
    changes: tuple[MigrationChange, ...]
    blocked: tuple[MigrationBlock, ...]
    failures: tuple[str, ...]

    @property
    def pending(self) -> bool:
        """Return whether the directory requires migration work or input repair."""
        return bool(self.changes or self.blocked or self.failures)


@dataclass(frozen=True)
class MigrationOutput:
    """Lines that a CLI writes to standard output and standard error."""

    output: tuple[str, ...]
    errors: tuple[str, ...]


@dataclass(frozen=True)
class MigrationApplication:
    """Records changed by an application and the backups that preserve their prior bytes."""

    changed: tuple[Path, ...]
    backups: tuple[tuple[Path, Path], ...]


class MigrationApplyError(ValueError):
    """A failed application with every recovery file and completed write made visible."""

    def __init__(
        self,
        message: str,
        *,
        backups: tuple[tuple[Path, Path], ...] = (),
        changed: tuple[Path, ...] = (),
    ) -> None:
        super().__init__(message)
        self.backups = backups
        self.changed = changed


@dataclass(frozen=True)
class _RecordSource:
    """One parsed record with the bytes and location needed to preview its change."""

    path: Path
    root: Path
    content: bytes
    record: Mapping[str, Any]


def _yaml_paths(root: Path) -> list[Path]:
    """Return visible YAML files of ``root`` in stable relative-path order."""
    paths = {*root.rglob("*.yml"), *root.rglob("*.yaml")}
    return sorted(
        path
        for path in paths
        if not any(part.startswith(".") for part in path.relative_to(root).parts)
    )


def _load(path: Path) -> tuple[bytes, Mapping[str, Any] | None, str | None]:
    """Return current bytes, a parsed mapping, and an actionable read failure."""
    if path.is_symlink():
        return b"", None, f"{path}: symbolic-link records are not migrated"
    try:
        content = path.read_bytes()
        text = content.decode("utf-8")
        value = yaml.safe_load(text)
    except (OSError, UnicodeDecodeError, yaml.YAMLError) as error:
        return b"", None, f"{path}: {error}"
    return content, value if isinstance(value, Mapping) else None, None


def _binding_span(text: str) -> tuple[int, int]:
    """Return the character span of the root ``_schema`` value."""
    root = yaml.compose(text)
    if not isinstance(root, MappingNode):
        raise ValueError("record does not hold a YAML mapping")
    bindings: list[ScalarNode] = []
    for key, value in root.value:
        if isinstance(key, ScalarNode) and key.value == "_schema":
            if not isinstance(value, ScalarNode):
                raise ValueError("_schema does not hold one scalar contract identifier")
            bindings.append(value)
    if not bindings:
        raise ValueError("record names no _schema contract")
    if len(bindings) != 1:
        raise ValueError("record contains multiple root _schema fields")
    binding = bindings[0]
    return binding.start_mark.index, binding.end_mark.index


def _replace_binding(content: bytes, current: str) -> bytes:
    """Return ``content`` with only the scalar value of its root binding replaced."""
    text = content.decode("utf-8")
    start, end = _binding_span(text)
    return (text[:start] + current + text[end:]).encode("utf-8")


def _diff(path: Path, root: Path, before: bytes, after: bytes) -> str:
    """Return a unified diff of one proposed binding change, named relative to ``root``."""
    relative = path.relative_to(root).as_posix()
    return "\n".join(
        difflib.unified_diff(
            before.decode("utf-8").splitlines(),
            after.decode("utf-8").splitlines(),
            fromfile=f"{relative} (current)",
            tofile=f"{relative} (migrated)",
            lineterm="",
        )
    )


def _backup_path(source: _RecordSource, previous: str) -> Path:
    """Return the versioned recovery path for one migrated record."""
    contract = previous.replace(":", "-").replace("@", "-").replace("/", "-")
    relative = source.path.relative_to(source.root)
    return source.root / ".gnomon-backup" / "migrations" / contract / relative


def _contract_type(contract: Mapping[str, Any]) -> str | None:
    """Return the record type fixed by a published contract."""
    properties = contract.get("properties")
    type_schema = properties.get("type") if isinstance(properties, Mapping) else None
    value = type_schema.get("const") if isinstance(type_schema, Mapping) else None
    return str(value) if value is not None else None


def _migration_target(
    path: Path,
    record: Mapping[str, Any],
    contracts: Mapping[str, Mapping[str, Any]],
    kinds_by_type: Mapping[str, str],
) -> tuple[str, str] | MigrationBlock | None:
    """Return the binding transition, a binding defect, or None for an irrelevant record."""
    record_type = str(record["type"])
    result: tuple[str, str] | MigrationBlock | None = None
    if record_type not in GENERATED_KINDS:
        previous_value = record.get("_schema")
        previous = str(previous_value) if previous_value is not None else None
        kind = kinds_by_type.get(record_type)
        if kind is None:
            if previous and previous.startswith("gnomon:"):
                result = MigrationBlock(
                    path,
                    previous,
                    None,
                    (f"record type {record_type!r} has no current Gnomon contract",),
                )
        else:
            current = identifier(kind, int(load_base(kind).get("x-version", 1)))
            published = contracts.get(previous or "")
            if previous == current:
                result = None
            elif previous is None:
                result = MigrationBlock(path, None, current, ("record names no _schema contract",))
            elif published is None:
                result = MigrationBlock(
                    path,
                    previous,
                    current,
                    (f"{previous} is not a published Gnomon contract",),
                )
            else:
                published_type = _contract_type(published)
                result = (
                    (previous, current)
                    if published_type == record_type
                    else MigrationBlock(
                        path,
                        previous,
                        current,
                        (
                            f"{previous} is a contract for {published_type!r}, "
                            f"not {record_type!r}",
                        ),
                    )
                )
    return result


def _propose_change(
    source: _RecordSource,
    previous: str,
    current: str,
) -> MigrationChange | MigrationBlock:
    """Return a binding-only proposal, or the current-contract defects that block it."""
    reasons = tuple(record_errors({**source.record, "_schema": current}))
    if reasons:
        return MigrationBlock(source.path, previous, current, reasons)
    try:
        migrated = _replace_binding(source.content, current)
    except ValueError as error:
        return MigrationBlock(source.path, previous, current, (str(error),))
    return MigrationChange(
        source.path,
        previous,
        current,
        _diff(source.path, source.root, source.content, migrated),
        source.content,
        migrated,
        _backup_path(source, previous),
    )


def render_migration_plan(
    plan: MigrationPlan, *, confirm_no_writes: bool = True
) -> MigrationOutput:
    """Return deterministic human-readable lines for a migration preview or review."""
    if not plan.pending:
        return MigrationOutput(("no migrations required; 0 files written",), ())
    output: list[str] = []
    errors: list[str] = []
    for change in plan.changes:
        relative = change.path.relative_to(plan.root)
        output += [
            f"{relative}: would update {change.previous} -> {change.current}",
            change.diff,
        ]
    for block in plan.blocked:
        relative = block.path.relative_to(plan.root)
        transition = (
            f"{block.previous} -> {block.current}"
            if block.current is not None
            else str(block.previous)
        )
        errors.append(f"{relative}: cannot migrate {transition}")
        errors += [f"  {reason}" for reason in block.reasons]
    errors += [f"cannot read: {failure}" for failure in plan.failures]
    summary = (
        f"{len(plan.changes)} migration proposed; {len(plan.blocked)} blocked; "
        f"{len(plan.failures)} unreadable"
    )
    output.append(f"{summary}; 0 files written" if confirm_no_writes else summary)
    return MigrationOutput(tuple(output), tuple(errors))


def plan_migration(root: Path) -> MigrationPlan:
    """Return the write-free migration plan of every authored Gnomon record below ``root``.

    A retained record is proposed for a binding-only migration when its unchanged content follows
    the current contract. A record that would violate the current contract is blocked with those
    violations, because choosing replacement research content belongs to the researcher.

    Raises
    ------
    ValueError
        If ``root`` is not an existing directory.
    """
    root = root.resolve()
    if not root.is_dir():
        raise ValueError(f"migration directory does not exist: {root}")
    contracts = published_contracts()
    kinds_by_type = record_kinds()
    changes: list[MigrationChange] = []
    blocked: list[MigrationBlock] = []
    failures: list[str] = []

    for path in _yaml_paths(root):
        content, record, failure = _load(path)
        if failure is not None:
            failures.append(failure)
            continue
        if record is None or "type" not in record:
            continue
        target = _migration_target(path, record, contracts, kinds_by_type)
        if isinstance(target, MigrationBlock):
            blocked.append(target)
        elif target is not None:
            proposal = _propose_change(_RecordSource(path, root, content, record), *target)
            if isinstance(proposal, MigrationChange):
                changes.append(proposal)
            else:
                blocked.append(proposal)
    return MigrationPlan(root, tuple(changes), tuple(blocked), tuple(failures))


def _open_source(change: MigrationChange, *, writable: bool, stage: str) -> int:
    """Open one regular source without following a symbolic link."""
    flags = os.O_RDWR if writable else os.O_RDONLY
    flags |= getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(change.path, flags)
    except OSError as error:
        raise ValueError(f"cannot open migration target {stage}: {change.path}: {error}") from error
    try:
        path_state = change.path.lstat()
        descriptor_state = os.fstat(descriptor)
        if stat.S_ISLNK(path_state.st_mode) or not stat.S_ISREG(descriptor_state.st_mode):
            raise ValueError(f"migration target is not a regular file {stage}: {change.path}")
        if not os.path.samestat(path_state, descriptor_state):
            raise ValueError(f"migration target changed {stage}: {change.path}")
    except (OSError, ValueError):
        os.close(descriptor)
        raise
    return descriptor


def _source_bytes(change: MigrationChange, stage: str) -> bytes:
    """Return current source bytes through a verified regular-file descriptor."""
    descriptor = _open_source(change, writable=False, stage=stage)
    with os.fdopen(descriptor, "rb") as stream:
        return stream.read()


def _write_change(change: MigrationChange) -> None:
    """Write one reviewed change through the descriptor that verified its current bytes."""
    descriptor = _open_source(change, writable=True, stage="before write")
    with os.fdopen(descriptor, "r+b") as stream:
        if stream.read() != change.before:
            raise ValueError(f"migration target changed before write: {change.path}")
        stream.seek(0)
        stream.write(change.after)
        stream.truncate()
        stream.flush()
        os.fsync(stream.fileno())
        try:
            path_state = change.path.lstat()
        except OSError as error:
            raise ValueError(f"migration target changed during write: {change.path}") from error
        if not os.path.samestat(path_state, os.fstat(stream.fileno())):
            raise ValueError(f"migration target changed during write: {change.path}")


def _check_backup_parents(root: Path, backup: Path, *, create: bool) -> None:
    """Reject symbolic links and non-directories along one recovery path."""
    relative = backup.relative_to(root)
    parent = root
    for part in relative.parts[:-1]:
        parent /= part
        if parent.is_symlink():
            raise ValueError(f"migration backup directory is a symbolic link: {parent}")
        if create:
            parent.mkdir(exist_ok=True)
        if not parent.is_dir():
            raise ValueError(f"migration backup parent is not a directory: {parent}")


def _create_backup(root: Path, change: MigrationChange) -> None:
    """Create one exact recovery file without following a pre-existing link."""
    _check_backup_parents(root, change.backup, create=True)
    _check_backup_parents(root, change.backup, create=False)
    try:
        with change.backup.open("xb") as stream:
            stream.write(change.before)
            stream.flush()
            os.fsync(stream.fileno())
    except FileExistsError as error:
        raise ValueError(
            f"migration backup already exists: {change.backup}; move it before applying again"
        ) from error


def apply_migration(plan: MigrationPlan) -> MigrationApplication:
    """Apply a reviewed migration plan after preserving every prior record.

    The plan is rejected when it contains a blocked or unreadable record, when a source changed
    after planning, or when a recovery target already exists. Every backup is created before any
    source is changed. A failure during the final writes therefore leaves the complete prior state
    recoverable.

    Parameters
    ----------
    plan
        The exact plan reviewed by the researcher.

    Returns
    -------
    MigrationApplication
        The changed records and their recovery paths.

    Raises
    ------
    MigrationApplyError
        If the plan is blocked or cannot be applied without losing current or recovery data. The
        error carries every recovery file created and every source completely changed before the
        failure.
    """
    backups: list[tuple[Path, Path]] = []
    changed: list[Path] = []
    try:
        if plan.blocked or plan.failures:
            raise ValueError("migration plan has blocked or unreadable records; 0 files written")
        for change in plan.changes:
            if _source_bytes(change, "after planning") != change.before:
                raise ValueError(f"migration target changed after planning: {change.path}")
        collision = next(
            (
                change.backup
                for change in plan.changes
                if change.backup.exists() or change.backup.is_symlink()
            ),
            None,
        )
        if collision is not None:
            raise ValueError(
                f"migration backup already exists: {collision}; move it before applying again"
            )
        for change in plan.changes:
            _create_backup(plan.root, change)
            backups.append((change.path, change.backup))
        for change in plan.changes:
            if _source_bytes(change, "after backup") != change.before:
                raise ValueError(f"migration target changed after backup: {change.path}")
        for change in plan.changes:
            _write_change(change)
            changed.append(change.path)
    except (OSError, ValueError) as error:
        raise MigrationApplyError(
            str(error), backups=tuple(backups), changed=tuple(changed)
        ) from error
    return MigrationApplication(tuple(changed), tuple(backups))
