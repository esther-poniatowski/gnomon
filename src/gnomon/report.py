"""
Reports of the findings of ``gnomon check``, rendered as YAML or as Markdown.

Both reports are stable: they hold no date and no absolute path, and they list the files, the
records and the findings in a fixed order, so that two runs on unchanged records write the same
file and a revision of the records shows as a difference of the report. The YAML report serves a
program or a later comparison; the Markdown report serves a reader, in an editor such as Obsidian,
where each file name links to the record that it names.

Functions
---------
render_yaml_report
    Render the findings as one YAML document grouped by file.
render_markdown_report
    Render the findings as a Markdown page grouped by file, with a link to each file.
"""

from __future__ import annotations

import os
from collections import Counter
from pathlib import Path, PurePosixPath
from typing import Any, Sequence

import yaml

from .sarif import Located


def _by_file(found: Sequence[Located]) -> dict[PurePosixPath, list[Located]]:
    """Group the findings by file, in the order of the files and then of the records."""
    groups: dict[PurePosixPath, list[Located]] = {}
    order = sorted(found, key=lambda x: (str(x.file), x.record or "", x.finding.rule.id, x.finding.locus,
                                         x.finding.discriminator, x.finding.text))
    for located in order:
        groups.setdefault(located.file, []).append(located)
    return groups


def render_yaml_report(found: Sequence[Located], checked: str, records: int) -> str:
    """Render the findings as one YAML document grouped by file.

    >>> print(render_yaml_report([], "my-problem", 3), end="")
    # Generated by `gnomon check`. Edit the records, not this file.
    checked: my-problem
    records: 3
    findings: 0
    by_rule: {}
    files: []
    """
    files: list[dict[str, Any]] = []
    for file, group in _by_file(found).items():
        files.append({
            "file": str(file),
            "findings": [
                {"record": x.record, "rule": x.finding.rule.id, "locus": x.finding.locus or "/",
                 **({"discriminator": x.finding.discriminator} if x.finding.discriminator else {}),
                 "message": x.finding.text}
                for x in group
            ],
        })
    document = {
        "checked": checked,
        "records": records,
        "findings": len(found),
        "by_rule": dict(sorted(Counter(x.finding.rule.id for x in found).items())),
        "files": files,
    }
    header = "# Generated by `gnomon check`. Edit the records, not this file.\n"
    return header + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)


def _cell(text: str) -> str:
    """Escape the characters that would break a cell of a Markdown table."""
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown_report(
    found: Sequence[Located], checked: str, records: int, root: Path | None = None, report_dir: Path | None = None
) -> str:
    """Render the findings as a Markdown page grouped by file, with a link to each file.

    ``root`` is the directory checked and ``report_dir`` the folder where the page is saved, so that
    each link resolves from there; without them, a link states the path relative to the root.

    >>> print(render_markdown_report([], "my-problem", 3), end="")
    # Check of my-problem
    <BLANKLINE>
    3 records checked, 0 findings.
    """
    lines = [f"# Check of {checked}", "", f"{records} records checked, {len(found)} findings."]
    counts = Counter(x.finding.rule.id for x in found)
    if counts:
        lines += ["", "| Rule | Findings |", "| --- | --- |"]
        lines += [f"| `{rule}` | {count} |" for rule, count in sorted(counts.items())]
    for file, group in _by_file(found).items():
        target = PurePosixPath(file if root is None or report_dir is None
                               else os.path.relpath(root.resolve() / file, report_dir.resolve()))
        lines += ["", f"## [{file}]({target.as_posix()})", "",
                  "| Record | Rule | Locus | Message |", "| --- | --- | --- | --- |"]
        lines += [f"| `{x.record}` | `{x.finding.rule.id}` | `{x.finding.locus or '/'}` | {_cell(x.finding.text)} |"
                  for x in group]
    return "\n".join(lines) + "\n"
