"""
The report of the findings of ``gnomon check``, rendered as YAML.

The report is stable: it holds no date and no absolute path, and it lists the files, the records
and the findings in a fixed order, so that two runs on unchanged records write the same file and a
revision of the records shows as a difference of the report. A renderer of the workspace, such as
Ekphrasis in Obsidian, presents it to a reader.

Functions
---------
render_yaml_report
    Render the findings as one YAML document grouped by file.
"""

from __future__ import annotations

from collections import Counter
from pathlib import PurePosixPath
from typing import TYPE_CHECKING, Any, Sequence

import yaml

from .findings import COMPUTED_INQUIRY_DIAGNOSIS
from .sarif import Located, issue_contract

if TYPE_CHECKING:
    from .check import FutureWork


def _by_file(found: Sequence[Located]) -> dict[PurePosixPath, list[Located]]:
    """Group the findings by file, in the order of the files and then of the records."""
    groups: dict[PurePosixPath, list[Located]] = {}
    order = sorted(
        found,
        key=lambda x: (
            str(x.file),
            x.record or "",
            x.finding.rule.id,
            x.finding.locus,
            x.finding.discriminator,
            x.finding.text,
        ),
    )
    for located in order:
        groups.setdefault(located.file, []).append(located)
    return groups


# Report metadata and future-work context are independent inputs to the stable serialized contract.
# pylint: disable-next=too-many-arguments
def render_yaml_report(
    found: Sequence[Located],
    checked: str,
    records: int,
    unfilled: Sequence[str] = (),
    *,
    scope: str | None = None,
    future_work: Sequence[FutureWork] = (),
) -> str:
    """Render the findings as one YAML document grouped by file, with the templates not yet filled.

    >>> print(render_yaml_report([], "my-problem", 3, ["my-problem/answer.yml"]), end="")
    # Generated by `gnomon check`. Edit the records, not this file.
    checked: my-problem
    records: 3
    findings: 0
    warnings: 0
    unfilled:
    - my-problem/answer.yml
    by_rule: {}
    files: []
    """
    files: list[dict[str, Any]] = []
    for file, group in _by_file(found).items():
        files.append(
            {
                "file": str(file),
                "findings": [
                    {
                        "record": x.record,
                        "rule": x.finding.rule.id,
                        "level": x.finding.rule.level,
                        "locus": x.finding.locus or "/",
                        "result_class": x.finding.rule.result_class,
                        **(
                            {"discriminator": x.finding.discriminator}
                            if x.finding.discriminator
                            else {}
                        ),
                        "message": x.finding.text,
                        "repair_condition": x.finding.rule.repair_condition,
                        "documentation_target": x.finding.rule.documentation_target,
                        **issue_contract(x),
                    }
                    for x in group
                ],
            }
        )
    document: dict[str, Any] = {
        "checked": checked,
        "records": records,
        "findings": sum(1 for x in found if x.finding.rule.level == "error"),
        "warnings": sum(1 for x in found if x.finding.rule.level == "warning"),
        "unfilled": sorted(unfilled),
        "by_rule": dict(sorted(Counter(x.finding.rule.id for x in found).items())),
        "files": files,
    }
    if scope is not None:
        document["scope"] = scope
        document["future"] = len(future_work)
        document["future_work"] = [
            {
                "due_scope": item.due_scope,
                "source_file": str(item.file),
                "record_identifier": item.record,
                "record_kind": item.kind,
                "field_path": item.path,
                "result_class": COMPUTED_INQUIRY_DIAGNOSIS,
                "message": item.message,
            }
            for item in future_work
        ]
    header = "# Generated by `gnomon check`. Edit the records, not this file.\n"
    return header + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)
