"""The field index: every field of every record type, with the row of the specification that
documents it, generated by `gnomon schemas` beside the contracts and the templates.

The schema test asserts that the index on disk is the generated one, so these tests check what the
index states.
"""

from __future__ import annotations

from pathlib import Path

from gnomon.fieldindex import field_index, index_fields
from gnomon.specnotes import RECORD_FIELDS


def test_only_the_fields_that_identify_a_record_have_no_documentation() -> None:
    undocumented = {
        (kind, field.path)
        for kind, fields in index_fields().items()
        for field in fields
        if field.note is None
    }
    assert undocumented and all(path in RECORD_FIELDS for _, path in undocumented), undocumented


def test_a_field_of_a_list_entry_takes_the_row_of_its_list() -> None:
    answer = {field.path: field for field in index_fields()["answer"]}
    assert answer["abstractions[].factor"].row == answer["abstractions"].row == "Abstractions"


def test_a_parent_named_only_through_its_children_takes_their_label() -> None:
    assessment = {field.path: field for field in index_fields()["assessment"]}
    assert assessment["tests"].row == "Tests"
    assert assessment["tests"].note == "specification/assessment.md"


def test_the_fields_are_in_alphabetical_order_of_their_paths() -> None:
    for fields in index_fields().values():
        paths = [field.path for field in fields]
        assert paths == sorted(paths)


def test_no_index_is_generated_outside_a_checkout(tmp_path: Path) -> None:
    assert field_index(tmp_path / "docs") is None
