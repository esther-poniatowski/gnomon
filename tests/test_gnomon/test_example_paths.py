"""Presence of the worked examples that the fixture-driven tests read.

The tests of symbol resolution, inquiry records and itineraries skip when they find no example
folder. A wrong location would therefore turn them into skips rather than failures. This test
fails instead. The vocabulary of each example is checked against its generated form.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from gnomon.vocabulary import load_problem, render_markdown, render_yaml

from .paths import EXAMPLES, EXPECTED_CASES

ROOT = Path(__file__).resolve().parents[2]


def test_every_worked_example_folder_is_present() -> None:
    """The examples folder exists and holds the folder of each expected inquiry."""
    assert EXAMPLES.is_dir(), f"the examples folder is missing: {EXAMPLES}"
    missing = [name for name in EXPECTED_CASES if not (EXAMPLES / name).is_dir()]
    assert not missing, f"example folders missing under {EXAMPLES}: {missing}"


@pytest.mark.parametrize("name", EXPECTED_CASES)
def test_the_vocabulary_of_each_example_is_its_generated_form(name: str) -> None:
    """The vocabulary of an example is generated by ``gnomon vocabulary``, so it changes with the
    records and the canonical operators; a stale copy misleads an author choosing a symbol."""
    folder = EXAMPLES / name
    if not (folder / "vocabulary.yml").is_file():
        pytest.skip("the example keeps no vocabulary")
    problem = load_problem(folder)
    assert (folder / "vocabulary.yml").read_text(encoding="utf-8") == render_yaml(problem)
    index = (folder / "_index.md").resolve().relative_to(ROOT.resolve()).as_posix()
    page = folder / "vocabulary.md"
    if page.is_file():
        assert page.read_text(encoding="utf-8") == render_markdown(problem, index_path=index)
